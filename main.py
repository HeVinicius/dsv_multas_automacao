print("Bem-vindos ao sistema de consulta de multas DSV-Digital")
print("Este sistema realiza a atutomatização da consulta de novas multas no carros indicados no período de 65 dias a partir da data atual.")
print("Desenvolvido por Victor v0.03")

# setups
usuario = " "  # seu usuário

senha = " "              # sua senha

# Caminhos dos arquivos
caminho_arquivo_placas = r" "  # arquivo com placas
nome_aba_placas = "placas"
caminho_arquivo_referencia = r" "  # arquivo com detalhes anteriores
nome_aba_referencia = "Detalhes"
novo_arquivo = r"resultado_consultas.xlsx"  # arquivo de saída

# Lê placas do arquivo
try:
    print("[LOG] Lendo planilha de placas...")
    if not os.path.exists(caminho_arquivo_placas):
        print(f"[ERRO] Arquivo não encontrado: {caminho_arquivo_placas}")
        placas = []
    else:
        df = pd.read_excel(caminho_arquivo_placas, sheet_name=nome_aba_placas)
        placas = df['PLACA'].dropna().astype(str).tolist()
        print(f"[LOG] Placas carregadas: {placas}")
except Exception as e:
    print(f"[ERRO] ao ler planilha: {e}")
    placas = []

#em testes de alterações o código possivelmente terá erro de lógica, necessário refaturar
# Lê detalhes de referência
if os.path.exists(caminho_arquivo_referencia):
    df_ref = pd.read_excel(caminho_arquivo_referencia, sheet_name=nome_aba_referencia)
    detalhes_referencia = dict(zip(df_ref['PLACA'], df_ref['DETALHES']))
else:
    detalhes_referencia = {}
    print(f"[ERRO] Arquivo de referência não encontrado: {caminho_arquivo_referencia}")

# Configuração do Selenium para Windows
print("[LOG] Inicializando WebDriver...")
chrome_driver_path = ChromeDriverManager().install()
servico = Service(executable_path=chrome_driver_path)
opcoes = webdriver.ChromeOptions()
opcoes.add_argument("--start-maximized")
opcoes.add_argument("--disable-blink-features=AutomationControlled")
opcoes.add_argument("--disable-infobars")
opcoes.add_argument("--disable-extensions")
opcoes.add_argument("--ignore-certificate-errors")
opcoes.add_argument("--headless=new")  # se quiser rodar sem abrir janela
opcoes.add_argument('--no-sandbox')
opcoes.add_argument('--disable-dev-shm-usage')
opcoes.binary_location = '/usr/bin/google-chrome'


navegador = webdriver.Chrome(service=servico, options=opcoes)
wait = WebDriverWait(navegador, 20)
print("[OK] Webdriver inicializado.")

#aqui o sistema realiza o login, a base das variaveis determinadas acima, necessário alteração em casos de refeturamento
# login
print("[LOG] Acessando página de login, por favor aguarde...")
navegador.get("https://cetdigital.prefeitura.sp.gov.br/#/login")
wait.until(EC.presence_of_element_located((By.NAME, "username"))).send_keys(usuario)
wait.until(EC.presence_of_element_located((By.NAME, "password"))).send_keys(senha)
wait.until(EC.element_to_be_clickable((By.ID, "btnEntrarSistema"))).click()
print("[OK] Login realizado.")

#Criação de saida de diretório caso ele não exista, se já existir ele irá sobrescrever o arquivo atual existente
output_dir = os.path.dirname(novo_arquivo)
if output_dir and not os.path.exists(output_dir):
    print(f"[LOG] Criando diretório de saída: {output_dir}")
    os.makedirs(output_dir)

#listas para armazenamento dos resultados
all_results = []

for idx, placa in enumerate(placas):
    print(f"\n[LOG] Consultando {placa}")
    try:
        campo = wait.until(EC.presence_of_element_located((By.ID, 'txtSearchRenavam')))
        campo.clear()
        campo.send_keys(placa)
        wait.until(EC.element_to_be_clickable((By.ID, 'btnLupa'))).click()
        wait.until(EC.element_to_be_clickable((By.XPATH, "//button[contains(@class,'btn-success') and contains(text(),'Pesquisar')]"))).click()
        time.sleep(1.2)

        # tentativas de captura das multas
        try:
            div_multas = wait.until(EC.presence_of_element_located((By.ID, "contentIndicacoes")))
            itens = div_multas.find_elements(By.XPATH, ".//div[contains(@class, 'item')]")
            detalhes_atual = []
            for item in itens:
                try:
                    detalhes = item.find_element(By.XPATH, ".//div[contains(@class, 'detalhes')]").text.strip()
                except Exception:
                    detalhes = item.text.strip()
                detalhes_atual.append(detalhes)
            detalhes_atual_str = " | ".join(detalhes_atual)
        except Exception as e:
            detalhes_atual_str = "Sem detalhes encontrados"

        # Aqui ele está realizando a comparação entre as existentes e as novas
        detalhes_antigo = detalhes_referencia.get(placa, "Sem referência")
        if detalhes_atual_str != detalhes_antigo:
            status = "ALTERADO"
        else:
            status = "SEM ALTERAÇÃO"

        all_results.append({'PLACA': placa, 'DETALHES_ANTIGO': detalhes_antigo, 'DETALHES_ATUAL': detalhes_atual_str, 'STATUS': status})

        # Log
        with open('log_consultas.txt', 'a', encoding='utf-8') as log:
            log.write(f"\n{'='*30}\nPlaca: {placa}\nStatus: {status}\nDetalhes antigo: {detalhes_antigo}\nDetalhes atual: {detalhes_atual_str}\n")

        time.sleep(0.7)
        #seleção de outro veículo
        try:
            wait.until(EC.element_to_be_clickable((By.XPATH, "//button[@ng-click='voltarSelecaoRenavam()' and contains(text(),'Selecionar outro veículo')]"))).click()
        except Exception:
            try:
                navegador.execute_script("document.querySelector(\"button[ng-click='voltarSelecaoRenavam()']\").click();")
            except Exception:
                pass
        time.sleep(0.7)
        if idx > 0 and idx % 80 == 0:
            print("[LOG] Pausa longa para evitar bloqueio do site...")
            time.sleep(4)
    except Exception as e:
        print(f"[ERRO] ao processar placa {placa}: {e}")
        all_results.append({'PLACA': placa, 'DETALHES_ANTIGO': '', 'DETALHES_ATUAL': '', 'STATUS': 'ERRO'})

#salva os resultados
print("[LOG] Salvando resultados...")
results_df = pd.DataFrame(all_results)
with pd.ExcelWriter(novo_arquivo, engine='openpyxl', mode='w') as writer:
    results_df.to_excel(writer, sheet_name='Resultados', index=False)
print("[OK] Resultados salvos.")

navegador.quit()
print("Consulta finalizada.")

